import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createClient } from "@supabase/supabase-js";

const [, , sourceEnvPath, outputPath, targetProfilesArg] = process.argv;

if (!sourceEnvPath || !outputPath || !targetProfilesArg) {
  console.error(
    "Usage: node scripts/generate-campus-lol-import.mjs <source .env.local> <output.sql> <comma-separated target profile IDs>",
  );
  process.exit(1);
}

const sourceEnv = Object.fromEntries(
  (await readFile(sourceEnvPath, "utf8"))
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#") && line.includes("="))
    .map((line) => {
      const separator = line.indexOf("=");
      return [line.slice(0, separator), line.slice(separator + 1)];
    }),
);

const sourceUrl = sourceEnv.NEXT_PUBLIC_SUPABASE_URL;
const sourceKey =
  sourceEnv.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ??
  sourceEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!sourceUrl || !sourceKey) {
  throw new Error("The source environment is missing its Supabase URL or public key.");
}

const source = createClient(sourceUrl, sourceKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

async function readAll(table) {
  const pageSize = 1000;
  const rows = [];

  for (let from = 0; ; from += pageSize) {
    const { data, error } = await source
      .from(table)
      .select("*")
      .range(from, from + pageSize - 1);

    if (error) throw new Error(`Could not read ${table}: ${error.message}`);
    rows.push(...(data ?? []));
    if (!data || data.length < pageSize) return rows;
  }
}

function deterministicUuid(value) {
  const bytes = Buffer.from(createHash("sha256").update(value).digest().subarray(0, 16));
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function sql(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

const [memes, votes] = await Promise.all([readAll("memes"), readAll("votes")]);
const memeById = new Map(memes.map((meme) => [meme.id, meme]));
const sourceUserIds = new Set(
  [...memes, ...votes]
    .map((row) => row.user_id)
    .filter((id) => typeof id === "string" && id.length > 0),
);
const targetProfileIds = targetProfilesArg.split(",").filter(Boolean);
const orderedSourceUserIds = [...sourceUserIds].sort();

if (targetProfileIds.length < orderedSourceUserIds.length + 1) {
  throw new Error(
    `Provide at least ${orderedSourceUserIds.length + 1} existing target profile IDs: one anonymous owner plus one for each source voter.`,
  );
}

const fallbackProfileId = targetProfileIds[0];
const profileMap = new Map(
  orderedSourceUserIds.map((sourceId, index) => [sourceId, targetProfileIds[index + 1]]),
);
const targetProfileFor = (sourceId) =>
  (typeof sourceId === "string" && profileMap.get(sourceId)) || fallbackProfileId;

const imageRows = memes
  .map((meme) => {
    const id = deterministicUuid(`campus-lol:image:${meme.id}`);
    const profileId = targetProfileFor(meme.user_id);
    return `(${sql(id)}, ${sql(profileId)}, ${sql(profileId)}, ${sql(profileId)}, ${sql(meme.image_url)}, ${sql(meme.prompt)}, true, false, ${sql(meme.created_at)}, ${sql(meme.created_at)})`;
  })
  .join(",\n  ");

const captionRows = memes
  .map((meme) => {
    const id = deterministicUuid(`campus-lol:caption:${meme.id}`);
    const imageId = deterministicUuid(`campus-lol:image:${meme.id}`);
    const profileId = targetProfileFor(meme.user_id);
    return `(${sql(id)}, ${sql(profileId)}, ${sql(profileId)}, ${sql(profileId)}, ${sql(imageId)}, ${sql(meme.caption)}, true, false, 0, ${sql(meme.created_at)}, ${sql(meme.created_at)})`;
  })
  .join(",\n  ");

const voteRows = votes
  .filter((vote) => memeById.has(vote.meme_id) && sourceUserIds.has(vote.user_id))
  .map((vote) => {
    const captionId = deterministicUuid(`campus-lol:caption:${vote.meme_id}`);
    const profileId = targetProfileFor(vote.user_id);
    return `(${sql(profileId)}, ${sql(profileId)}, ${sql(profileId)}, ${sql(captionId)}, ${Number(vote.vote_value)}, false, ${sql(vote.created_at)}, ${sql(vote.created_at)})`;
  })
  .join(",\n  ");

const migration = `-- Generated by scripts/generate-campus-lol-import.mjs.
-- Source data is read through the Campus LOL public Supabase API.
-- Authentication records, passwords, and email addresses are intentionally excluded.
-- Source users are mapped to existing anonymous teaching profiles in the target project.

begin;

insert into public.images (
  id, profile_id, created_by_user_id, modified_by_user_id, url,
  additional_context, is_public, is_common_use,
  created_datetime_utc, modified_datetime_utc
) values
  ${imageRows}
on conflict (id) do update set
  url = excluded.url,
  additional_context = excluded.additional_context,
  is_public = true,
  modified_datetime_utc = excluded.modified_datetime_utc;

insert into public.captions (
  id, profile_id, created_by_user_id, modified_by_user_id, image_id, content,
  is_public, is_featured, like_count,
  created_datetime_utc, modified_datetime_utc
) values
  ${captionRows}
on conflict (id) do update set
  content = excluded.content,
  image_id = excluded.image_id,
  is_public = true,
  modified_datetime_utc = excluded.modified_datetime_utc;

${voteRows ? `insert into public.caption_votes (
  profile_id, created_by_user_id, modified_by_user_id, caption_id, vote_value,
  is_from_study, created_datetime_utc, modified_datetime_utc
)
select
  imported.profile_id::uuid,
  imported.created_by_user_id::uuid,
  imported.modified_by_user_id::uuid,
  imported.caption_id::uuid,
  imported.vote_value::integer,
  imported.is_from_study::boolean,
  imported.created_datetime_utc::timestamptz,
  imported.modified_datetime_utc::timestamptz
from (values
  ${voteRows}
) as imported(
  profile_id, created_by_user_id, modified_by_user_id, caption_id, vote_value,
  is_from_study, created_datetime_utc, modified_datetime_utc
)
where not exists (
  select 1
  from public.caption_votes existing
  where existing.profile_id = imported.profile_id::uuid
    and existing.caption_id = imported.caption_id::uuid
);` : "-- No source votes were available."}

commit;
`;

await writeFile(outputPath, migration, "utf8");
console.log(`Prepared ${memes.length} memes and ${votes.length} votes for import.`);
