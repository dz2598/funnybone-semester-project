begin;

create table if not exists public.meme_comments (
  id bigint generated by default as identity primary key,
  meme_id bigint not null references public.memes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null,
  author_avatar_url text,
  content text not null check (char_length(btrim(content)) between 1 and 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists meme_comments_meme_created_idx
  on public.meme_comments (meme_id, created_at);

alter table public.meme_comments enable row level security;

drop policy if exists "Signed in users can read meme comments"
  on public.meme_comments;
create policy "Signed in users can read meme comments"
  on public.meme_comments for select
  to authenticated
  using (true);

drop policy if exists "Users can create their own meme comments"
  on public.meme_comments;
create policy "Users can create their own meme comments"
  on public.meme_comments for insert
  to authenticated
  with check (user_id = auth.uid());

drop policy if exists "Users can delete their own meme comments"
  on public.meme_comments;
create policy "Users can delete their own meme comments"
  on public.meme_comments for delete
  to authenticated
  using (
    user_id = auth.uid()
    or exists (
      select 1
      from public.profiles
      where profiles.id = auth.uid()
        and profiles.is_superadmin = true
    )
  );

commit;
